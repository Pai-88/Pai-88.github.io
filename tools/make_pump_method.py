# assumptions the design pre-registers, to be replaced by measurement
ETA = 0.9                 # fill efficiency
T_REOPEN = 0.15           # s, silicone 5/7
T_ROTOR = (0.05, 0.15, 0.3)   # N m: the range for a 1 mm wall and three rollers, and the middle of it
SPARE = 0.15              # the method's 10 to 20 percent over the bag volume
TURNS = 60
STACK = dict(liner=0.10, pitch=0.10, bearing=0.005, post=0.10)   # ± mm, from the pack's tolerance budget
FIT_LIMIT = 0.2

WALL = (P["TUBE_OD"] - P["TUBE_ID"]) / 2
GAP = 2 * WALL * (1 - P["SQUEEZE"])
R_ROLLER = P["BRG_OD"] / 2
R_RACE = P["R_TUBE"] + P["TUBE_OD"] / 2
R_PITCH = R_RACE - GAP - R_ROLLER
AREA = math.pi * P["TUBE_ID"] ** 2 / 4
FLAT_W = math.pi * P["TUBE_ID"] / 2 + WALL
ROLLER_W = P["BRG_PER_ROLLER"] * P["BRG_W"]
RATIO = P["WHEEL_T"] / P["PINION_T"]
CD = P["MODULE"] * (P["PINION_T"] + P["WHEEL_T"]) / 2 + P["CD_ALLOW"]
MAX_RPS = 1 / (P["N_ROLLERS"] * T_REOPEN)
WRAP_RATIO = P["WRAP_DEG"] / (360 / P["N_ROLLERS"])
BEND_LO, BEND_HI = 4 * P["TUBE_OD"], 6 * P["TUBE_OD"]
V_REV = AREA * 2 * math.pi * P["R_TUBE"] * ETA / 1000           # mL per rotor revolution
V_KEY = V_REV * RATIO
V_60 = V_KEY * TURNS
T_RUN = TURNS / (MAX_RPS / RATIO)
REACH = R_PITCH + R_ROLLER
X_CLEAR = math.sqrt(REACH ** 2 - P["R_TUBE"] ** 2)             # where the roller reach crosses the tube leg
STACK_SUM = sum(STACK.values())
FORCE_PER_NM = RATIO / (P["KEY_LONG_ARM"] / 1000)
SQUEEZE_OF = lambda gap: max(0.0, 1 - gap / (2 * WALL))
MOUNT_DX = max(x for x, _ in P["MOUNT_XY"]) - min(x for x, _ in P["MOUNT_XY"])
MOUNT_DY = max(y for _, y in P["MOUNT_XY"]) - min(y for _, y in P["MOUNT_XY"])


def r_tube_for(volume_ml, G):
    """Tube centre-line radius so that 60 key turns through ratio G deliver volume_ml with the spare."""
    v_rev = volume_ml * 1000 * (1 + SPARE) / (TURNS * G)
    return v_rev / (AREA * 2 * math.pi * ETA)


def v60_at(G):
    return V_REV * G * TURNS



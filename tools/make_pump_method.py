def race_svg():
    """The race, rollers and tube to scale, with the three radii that add to R_race along the horizontal."""
    s = 2.55
    cx, cy = 318, 168
    rr, rp, rb, rt = R_RACE * s, R_PITCH * s, R_ROLLER * s, P["R_TUBE"] * s
    half = math.radians(P["WRAP_DEG"] / 2)
    big = 1 if P["WRAP_DEG"] > 180 else 0
    pt = lambda r, a: (cx + r * math.cos(a), cy + r * math.sin(a))
    a0, a1 = math.pi - half, math.pi + half          # race centred on -x: from the bottom round the left to the top
    leg = 44 * s
    def arc(r, w, col, dash="", op=""):
        (x0, y0), (x1, y1) = pt(r, a0), pt(r, a1)
        return (f'<path d="M{x0 + leg:.1f},{y0:.1f} L{x0:.1f},{y0:.1f} A{r:.1f},{r:.1f} 0 {big},1 {x1:.1f},{y1:.1f} L{x1 + leg:.1f},{y1:.1f}" '
                f'fill="none" stroke="{col}" stroke-width="{w}"{dash}{op}/>')
    tube = arc(rt, P["TUBE_OD"] * s, "var(--accent)", op=' stroke-opacity=".25"') + arc(rt, 1.1, "var(--accent)", ' stroke-dasharray="4 4"')
    (x0, y0), (x1, y1) = pt(rr, a0), pt(rr, a1)
    race = (f'<path d="M{x0:.1f},{y0:.1f} A{rr:.1f},{rr:.1f} 0 {big},1 {x1:.1f},{y1:.1f}" fill="none" stroke="var(--ink)" stroke-width="2.4"/>'
            f'<path d="M{x0 + leg:.1f},{y0 + rr - rt:.1f} L{x0:.1f},{y0 + rr - rt:.1f} M{x1 + leg:.1f},{y1 - rr + rt:.1f} L{x1:.1f},{y1 - rr + rt:.1f}" fill="none" stroke="var(--ink)" stroke-width="2.4"/>')
    pitch = f'<circle cx="{cx}" cy="{cy}" r="{rp:.1f}" fill="none" stroke="var(--rule-2)" stroke-width=".8" stroke-dasharray="3 5"/>'
    rollers, spokes = [], []
    for i in range(P["N_ROLLERS"]):
        a = math.pi + 2 * math.pi * i / P["N_ROLLERS"]
        x, y = pt(rp, a)
        spokes.append(f'<line x1="{cx}" y1="{cy}" x2="{x:.1f}" y2="{y:.1f}" stroke="var(--rule-2)" stroke-width="7" stroke-linecap="round"/>')
        rollers.append(f'<circle cx="{x:.1f}" cy="{y:.1f}" r="{rb:.1f}" fill="var(--raise)" stroke="var(--ink-2)" stroke-width="1.4"/>'
                       f'<circle cx="{x:.1f}" cy="{y:.1f}" r="{P["BRG_ID"] / 2 * s:.1f}" fill="none" stroke="var(--ink-2)" stroke-width="1"/>'
                       f'<circle cx="{x:.1f}" cy="{y:.1f}" r="{P["PIN_D"] / 2 * s:.1f}" fill="var(--rule-2)"/>')
    hub = f'<circle cx="{cx}" cy="{cy}" r="{P["PIN_D"] / 2 * s:.1f}" fill="var(--raise)" stroke="var(--ink-2)" stroke-width="1.4"/>'
    # dimension chain below the race, along -x from the axis: R_pitch, R_roller, gap; R_race under it
    def dim(y, r0, r1, label, col="var(--ink-2)", above=True, lx=None, anchor="middle"):
        xa, xb = cx - r0 * s, cx - r1 * s
        ty = y - 7 if above else y + 15
        tx = (xa + xb) / 2 if lx is None else lx
        return (f'<line x1="{xa:.1f}" y1="{y}" x2="{xb:.1f}" y2="{y}" stroke="{col}" stroke-width="1"/>'
                f'<line x1="{xa:.1f}" y1="{y - 4}" x2="{xa:.1f}" y2="{y + 4}" stroke="{col}" stroke-width="1"/>'
                f'<line x1="{xb:.1f}" y1="{y - 4}" x2="{xb:.1f}" y2="{y + 4}" stroke="{col}" stroke-width="1"/>'
                f'<text x="{tx:.1f}" y="{ty}" text-anchor="{anchor}" fill="{col}" font-size="11">{label}</text>')
    ext = lambda x, y0, y1: f'<line x1="{x:.1f}" y1="{y0:.1f}" x2="{x:.1f}" y2="{y1:.1f}" stroke="var(--rule-2)" stroke-width=".7" stroke-dasharray="2 3"/>'
    yd = cy + rr + 30
    dims = (ext(cx, cy, yd + 46) + ext(cx - rr, cy + rr, yd + 46) + ext(cx - rp, cy, yd + 6) + ext(cx - REACH * s, cy, yd + 6)
            + dim(yd, 0, R_PITCH, f"R pitch {R_PITCH:.1f}")
            + dim(yd, R_PITCH, REACH, f"R roller {R_ROLLER:.0f}", above=False)
            + dim(yd, REACH, R_RACE, f"gap {GAP:.2f}", col="var(--accent)", lx=cx - rr - 8, anchor="end")
            + dim(yd + 40, 0, R_RACE, f"R race {R_RACE:.1f} = {R_PITCH:.1f} + {R_ROLLER:.0f} + {GAP:.2f}", above=False))
    (wx0, wy0), (wx1, wy1) = pt(rr + 16, a0), pt(rr + 16, a1)
    wrap = (f'<path d="M{wx0:.1f},{wy0:.1f} A{rr + 16:.1f},{rr + 16:.1f} 0 {big},1 {wx1:.1f},{wy1:.1f}" fill="none" stroke="var(--ink-3)" stroke-width=".8" stroke-dasharray="2 4"/>'
            f'<text x="{cx - rr - 24:.0f}" y="{cy - rr - 20:.0f}" fill="var(--ink-3)" font-size="11">wrap W = {P["WRAP_DEG"]:.0f}°, {P["N_ROLLERS"]} rollers</text>')
    labels = (f'<text x="{x0 + leg + 6:.0f}" y="{y0 + 4:.0f}" fill="var(--accent)" font-size="11">tube</text>'
              f'<text x="{x1 + leg + 6:.0f}" y="{y1 + 4:.0f}" fill="var(--accent)" font-size="11">tube</text>'
              f'<text x="{cx + 16}" y="{cy - 14}" fill="var(--ink-2)" font-size="11">rotor axis</text>'
              f'<text x="{cx + rp * math.cos(math.pi / 3) + rb + 4:.0f}" y="{cy + rp * math.sin(math.pi / 3) + 4:.0f}" fill="var(--ink-2)" font-size="11">6000 bearing, two high</text>')
    label = (f"The race seen along the rotor axis, to scale: a {P['WRAP_DEG']:.0f} degree arc of radius {R_RACE:.1f} mm on the left, "
             f"{P['N_ROLLERS']} bearings of {P['BRG_OD']:.0f} mm on a {R_PITCH:.1f} mm pitch radius, the tube pressed to a {GAP:.2f} mm gap and leaving to the right on two straight legs.")
    w = int(cx + leg + 110)
    return (f'<svg viewBox="0 0 {w} {int(yd + 64)}" role="img" aria-label="{label}" style="max-width:40rem">'
            f'{tube}{race}{pitch}{"".join(spokes)}{"".join(rollers)}{hub}{dims}{wrap}{labels}</svg>')


def renders():
    """The two renders from the pack as webp plates, when the pack is here; otherwise the files already in assets."""
    from PIL import Image, ImageChops
    out = ROOT / "assets" / "img"
    for name, src, crop_top in (("pump_open", "view_open.png", 70), ("pump_plan", "sec_plan.png", 48)):
        f = PACK / src
        if not f.exists():
            continue
        im = Image.open(f).convert("RGBA")
        bg = Image.new("RGBA", im.size, (255, 255, 255, 255))
        im = Image.alpha_composite(bg, im).convert("RGB")
        im = im.crop((0, crop_top, im.width, im.height))
        box = ImageChops.difference(im, Image.new("RGB", im.size, (255, 255, 255))).getbbox()
        if box:
            pad = 16
            im = im.crop((max(0, box[0] - pad), max(0, box[1] - pad), min(im.width, box[2] + pad), min(im.height, box[3] + pad)))
        if im.width > 1600:
            im = im.resize((1600, round(im.height * 1600 / im.width)), Image.LANCZOS)
        im.save(out / f"{name}.webp", "WEBP", quality=86, method=6)
        print(f"wrote assets/img/{name}.webp {im.size}")


